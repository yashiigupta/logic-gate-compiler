/**
 * PHASE 6 — CODE GENERATION
 * ---------------------------------------------------------------
 * Input : optimized three-address code + symbol table
 * Output:
 *   1. Target code   — a synthesizable VERILOG module (hardware description)
 *   2. Truth table   — value of every output for every input combination
 *   3. Equivalence   — proof that optimized code == unoptimized code
 *   4. Gate count    — before vs after optimization
 *
 * (The circuit drawing is rendered from the same optimized code by
 *  src/ui/diagrams.js.)
 */

const MAX_TRUTH_TABLE_ROWS = 1024;

function generateVerilog(code, inputs, outputs) {
  const verilogOperand = (a) => (a === "0" ? "1'b0" : a === "1" ? "1'b1" : a);
  const expression = (i) => {
    const [a, b] = i.args.map(verilogOperand);
    switch (i.op) {
      case "COPY": return a;
      case "NOT":  return `~${a}`;
      case "AND":  return `${a} & ${b}`;
      case "OR":   return `${a} | ${b}`;
      case "XOR":  return `${a} ^ ${b}`;
      case "NAND": return `~(${a} & ${b})`;
      case "NOR":  return `~(${a} | ${b})`;
    }
  };

  const ports = [...inputs.map((n) => `input ${n}`), ...outputs.map((n) => `output ${n}`)];
  const wires = code.map((i) => i.dest).filter((d) => !outputs.includes(d));

  const lines = [];
  lines.push("// Generated by Logic Gate Compiler");
  lines.push(`module circuit(${ports.join(", ")});`);
  if (wires.length) lines.push(`  wire ${wires.join(", ")};`);
  for (const i of code) lines.push(`  assign ${i.dest} = ${expression(i)};`);
  lines.push("endmodule");
  return lines.join("\n");
}

function buildTruthTable(originalCode, optimizedCode, inputs, outputs) {
  const total = 2 ** inputs.length;
  const rowCount = Math.min(total, MAX_TRUTH_TABLE_ROWS);
  const rows = [];
  let equivalent = true;

  for (let k = 0; k < rowCount; k++) {
    // Row k: input bits of k, first input = most significant bit
    const values = {};
    inputs.forEach((name, idx) => { values[name] = (k >> (inputs.length - 1 - idx)) & 1; });

    const optimizedEnv = runIR(optimizedCode, values);
    const originalEnv = runIR(originalCode, values);
    const outs = outputs.map((o) => optimizedEnv[o]);
    if (outputs.some((o) => optimizedEnv[o] !== originalEnv[o])) equivalent = false;

    rows.push({ inputs: inputs.map((n) => values[n]), outputs: outs });
  }
  return { inputs, outputs, rows, truncated: total > rowCount, totalRows: total, equivalent };
}

function countGates(code) {
  return code.filter((i) => i.op !== "COPY").length;
}

function generateCode(originalCode, optimizedCode, symbols) {
  const inputs = symbols.filter((s) => s.kind === "input").map((s) => s.name);
  const outputs = symbols.filter((s) => s.kind === "output").map((s) => s.name);
  return {
    verilog: generateVerilog(optimizedCode, inputs, outputs),
    truthTable: buildTruthTable(originalCode, optimizedCode, inputs, outputs),
    stats: {
      gatesBefore: countGates(originalCode),
      gatesAfter: countGates(optimizedCode),
      instructionsBefore: originalCode.length,
      instructionsAfter: optimizedCode.length,
    },
    inputs,
    outputs,
  };
}
